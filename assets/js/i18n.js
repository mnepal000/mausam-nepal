MN.lang = localStorage.getItem("mn-lang") || "en";

MN.t = function (key, vars) {
  let s = (MN.I18N[MN.lang] && MN.I18N[MN.lang][key]) || MN.I18N.en[key] || key;
  if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
  return s;
};

/* Localize digits: 2026 -> २०२६ when Nepali */
MN.num = function (v, decimals) {
  if (v === null || v === undefined || isNaN(v)) return "-";
  let s = (decimals !== undefined) ? Number(v).toFixed(decimals) : String(v);
  if (MN.lang === "ne") {
    const d = ["०","१","२","३","४","५","६","७","८","९"];
    s = s.replace(/[0-9]/g, ch => d[+ch]);
  }
  return s;
};

MN.setLang = function (lang) {
  MN.lang = (lang === "ne") ? "ne" : "en";
  localStorage.setItem("mn-lang", MN.lang);
  document.documentElement.lang = (MN.lang === "ne") ? "ne" : "en";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = MN.t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = MN.t(el.getAttribute("data-i18n-ph"));
  });
  const tg = document.getElementById("lang-toggle");
  if (tg) tg.textContent = (MN.lang === "ne") ? "EN" : "ने";
  if (window.MNApp && MNApp.refresh) MNApp.refresh();
};
